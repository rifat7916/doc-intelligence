#!/usr/bin/env python3
"""Run the backend test suite and write docs/test-results.md (counts per module, coverage per file).

  python scripts/make_test_report.py                                   # SQLite (no services needed)
  python scripts/make_test_report.py --postgres postgresql://user:pw@localhost:5432/db   # also run on PostgreSQL + pgvector
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import platform
import subprocess
import sys
import tempfile
import time
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
WHAT = {
    "test_common": "number, date and currency parsing; never invents a year",
    "test_filetype": "file type from content (magic bytes); empty, spoofed and corrupt files",
    "test_processing_pdf": "PDF text layer, scanned and mixed PDFs, progress, corrupt / truncated / password-protected PDFs, page limits",
    "test_ocr_images": "OCR on PNG / JPG / TIFF: noise, skew, sideways pages, low resolution, blank, transparency, corrupt, per-frame failure",
    "test_spreadsheets": "XLSX / XLS / CSV: sheets, encodings, delimiters, column synonyms, grouping rows into invoices, corrupt files",
    "test_extraction": "regex rules, Gemini client with a mocked SDK (retries, model fallback, outage, garbage), anti-hallucination grounding, invoice segmentation",
    "test_embeddings": "offline and Gemini embedders (batching, retry, normalisation)",
    "test_validation": "every validation rule, tolerance, duplicate detection",
    "test_pipeline": "end-to-end processing per file type, history, idempotency, stuck-job recovery, hostile content, degradations",
    "test_api": "all endpoints: upload, list, status, results, corrections, approve, reprocess, preview, auth, rate limit, CORS, upload attacks",
    "test_search": "keyword / semantic / hybrid search, filters, pagination, hostile queries, reindex",
    "test_failures": "cross-cutting failure scenarios and concurrent workers (PostgreSQL)",
    "test_secret_scan": "the repository's secret scanner and a scan of the repository itself",
    "test_check_gemini": "the first-run Gemini self-check script",
}


def run_suite(db_url: str | None, coverage: bool) -> dict:
    tmp = tempfile.mkdtemp()
    junit, cov_json = f"{tmp}/junit.xml", f"{tmp}/cov.json"
    cmd = [sys.executable, "-m", "pytest", "-o", "addopts=-p no:cacheprovider", "-q", f"--junitxml={junit}"]
    if coverage:
        cmd += ["--cov=app", f"--cov-report=json:{cov_json}"]
    env = {k: v for k, v in os.environ.items() if k != "TEST_DATABASE_URL"}
    if db_url:
        env["TEST_DATABASE_URL"] = db_url
    t0 = time.time()
    proc = subprocess.run(cmd, cwd=BACKEND, env=env, capture_output=True, text=True)
    seconds = time.time() - t0
    per: dict[str, dict] = defaultdict(lambda: {"passed": 0, "failed": 0, "skipped": 0, "seconds": 0.0})
    failures = []
    for tc in ET.parse(junit).getroot().iter("testcase"):
        mod = tc.get("classname", "").split(".")[1] if "." in tc.get("classname", "") else tc.get("classname", "?")
        kind = "failed" if tc.find("failure") is not None or tc.find("error") is not None else \
            "skipped" if tc.find("skipped") is not None else "passed"
        per[mod][kind] += 1
        per[mod]["seconds"] += float(tc.get("time", 0))
        if kind == "failed":
            failures.append(f"{mod}::{tc.get('name')}")
    cov = json.loads(Path(cov_json).read_text()) if coverage and Path(cov_json).exists() else None
    return {"per": dict(per), "seconds": seconds, "failures": failures, "cov": cov, "returncode": proc.returncode,
            "db": "PostgreSQL + pgvector" if db_url else "SQLite"}


def totals(res: dict) -> tuple[int, int, int]:
    return (sum(v["passed"] for v in res["per"].values()), sum(v["failed"] for v in res["per"].values()),
            sum(v["skipped"] for v in res["per"].values()))


def table(headers: list[str], rows: list[list]) -> str:
    return "\n".join(["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"] +
                     ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--postgres", default=None, help="also run the whole suite against this PostgreSQL URL")
    ap.add_argument("--out", default=str(ROOT / "docs" / "test-results.md"))
    args = ap.parse_args()
    runs = [run_suite(None, True)]
    if args.postgres:
        runs.append(run_suite(args.postgres, False))

    lines = ["# Automated test results", "",
             f"_Generated by `scripts/make_test_report.py` on {dt.datetime.now().strftime('%Y-%m-%d %H:%M')} "
             f"(Python {platform.python_version()}, {platform.system()}). Re-run: `make test-report`._", "",
             "## Summary", "",
             table(["Database", "Passed", "Failed", "Skipped", "Duration"],
                   [[r["db"], totals(r)[0], totals(r)[1], totals(r)[2], f"{r['seconds']:.0f} s"] for r in runs]), "",
             "One test is skipped on SQLite because it needs PostgreSQL row locks (two workers must not process the same document)."
             if args.postgres or True else "", ""]
    for r in runs:
        if r["failures"]:
            lines += [f"**Failures on {r['db']}:** " + ", ".join(r["failures"]), ""]
    main_run = runs[0]
    lines += ["## Tests per module", "",
              table(["Module", "Tests", "Passed", "Failed", "Skipped", "Seconds", "What it checks"],
                    [[m, sum(v[k] for k in ("passed", "failed", "skipped")), v["passed"], v["failed"], v["skipped"],
                      f"{v['seconds']:.1f}", WHAT.get(m, "")] for m, v in sorted(main_run["per"].items())]), ""]
    cov = main_run["cov"]
    if cov:
        t = cov["totals"]
        rows = [[f.replace("\\", "/"), d["summary"]["num_statements"], d["summary"]["missing_lines"], f"{d['summary']['percent_covered']:.0f}%"]
                for f, d in sorted(cov["files"].items())]
        lines += ["## Code coverage (`app/`, measured on the SQLite run)", "",
                  f"**{t['percent_covered']:.0f}%** of {t['num_statements']} statements. Lowest-covered files first:", "",
                  table(["File", "Statements", "Missed", "Covered"], sorted(rows, key=lambda r: int(r[3][:-1]))[:12]), ""]
    lines += ["## Reproduce", "", "```bash", "cd backend && pip install -r requirements-dev.txt",
              "python -m pytest                     # SQLite, no services needed",
              "TEST_DATABASE_URL=postgresql://docintel:docintel@localhost:5432/docintel python -m pytest   # PostgreSQL + pgvector",
              "python -m pytest --cov=app           # with coverage", "```", ""]
    Path(args.out).write_text("\n".join(lines))
    ok = all(r["returncode"] == 0 for r in runs)
    print(("PASS" if ok else "FAIL"), " | ".join(f"{r['db']}: {totals(r)[0]} passed, {totals(r)[1]} failed, {totals(r)[2]} skipped" for r in runs), f"-> {args.out}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
