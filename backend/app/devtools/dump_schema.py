"""Print the PostgreSQL DDL:  python -m app.devtools.dump_schema > ../docs/schema.sql"""
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app import models  # noqa: F401
from app.db import Base


def main() -> None:
    d = postgresql.dialect()
    out = ["-- PostgreSQL 16 + pgvector. Generated by: python -m app.devtools.dump_schema",
           "CREATE EXTENSION IF NOT EXISTS vector;", ""]
    for t in Base.metadata.sorted_tables:
        out.append(str(CreateTable(t).compile(dialect=d)).strip() + ";")
        out += [str(CreateIndex(ix).compile(dialect=d)).strip() + ";" for ix in sorted(t.indexes, key=lambda i: i.name)]
        out.append("")
    out += ["-- keyword search: full-text index over the extracted text of every page",
            "CREATE INDEX IF NOT EXISTS ix_pages_fts ON document_pages USING GIN (to_tsvector('simple'::regconfig, text));",
            "-- semantic search: approximate nearest-neighbour index (cosine distance)",
            "CREATE INDEX IF NOT EXISTS ix_chunks_embedding ON chunks USING hnsw (embedding vector_cosine_ops);"]
    print("\n".join(out))


if __name__ == "__main__":
    main()
